#!/usr/bin/env python3
import re
import subprocess
import sys

so = sys.argv[1]
out_s = sys.argv[2]
out_c = sys.argv[3]

def undefined_gl(so):
    out = subprocess.run(["readelf", "--dyn-syms", "-W", so],
                         capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 8:
            continue
        if parts[6] != "UND":
            continue
        name = parts[7].split("@")[0]
        if not name:
            continue
        if name.startswith("gl") and not name.startswith("glX") and not name.startswith("egl"):
            if re.fullmatch(r"[A-Za-z0-9_]+", name):
                names.add(name)
    return sorted(names)

names = undefined_gl(so)
print(f"GL-bridge: {len(names)} GL symbols from {so}")

with open(out_s, "w") as f:
    f.write("# generated by gen_gl.py - SuperCraft GL bridge thunks\n")
    f.write(".text\n")
    for n in names:
        f.write(f".globl {n}\n")
        f.write(f".type {n},@function\n")
        f.write(f"{n}:\n")
        f.write(f"  jmp *{n}_slot(%rip)\n")
        f.write(f".size {n},.-{n}\n")
        f.write(f".data\n")
        f.write(f".globl {n}_slot\n")
        f.write(f".hidden {n}_slot\n")
        f.write(f"{n}_slot:\n")
        f.write("  .quad 0\n")
        f.write(".text\n")

with open(out_c, "w") as f:
    f.write("/* generated by gen_gl.py - SuperCraft GL bridge binding table */\n")
    f.write("#include <stdio.h>\n#include <string.h>\n")
    f.write("extern void *sup_gl_resolve(const char *name);\n")
    for n in names:
        f.write(f"extern void *{n}_slot;\n")
    f.write("\nstatic void gl_stub(void) {\n")
    f.write("    static int once = 0;\n")
    f.write("    if (!once) { once = 1; fprintf(stderr, \"GL> called unresolved GL function\\n\"); }\n")
    f.write("}\n")
    f.write("\nstatic void __attribute__((constructor)) sup_bridge_bind(void) {\n")
    f.write("    const char *names[] = {\n")
    for n in names:
        f.write(f'        "{n}",\n')
    f.write("    };\n    void **slots[] = {\n")
    for n in names:
        f.write(f"        &{n}_slot,\n")
    f.write("    };\n")
    f.write("    int n = (int)(sizeof(names) / sizeof(names[0]));\n")
    f.write("    int resolved = 0, unresolved = 0;\n")
    f.write("    for (int i = 0; i < n; ++i) {\n")
    f.write("        void *r = sup_gl_resolve(names[i]);\n")
    f.write("        if (r) { *slots[i] = r; resolved++; }\n")
    f.write("        else { *slots[i] = (void *)gl_stub; unresolved++; }\n")
    f.write("    }\n")
    f.write("    fprintf(stderr, \"GL> bridge bound %d/%d functions (%d unresolved)\\n\",\n")
    f.write("            resolved, n, unresolved);\n")
    f.write("    fflush(stderr);\n")
    f.write("}\n")
    f.write("\nvoid *sup_gl_slot_lookup(const char *name) {\n")
    f.write("    if (!name) return NULL;\n")
    f.write("    static const char *names[] = {\n")
    for n in names:
        f.write(f'        "{n}",\n')
    f.write("    };\n    void **slots[] = {\n")
    for n in names:
        f.write(f"        &{n}_slot,\n")
    f.write("    };\n")
    f.write("    size_t cnt = sizeof(names) / sizeof(names[0]);\n")
    f.write("    for (size_t i = 0; i < cnt; ++i) {\n")
    f.write("        if (strcmp(name, names[i]) == 0) return *slots[i];\n")
    f.write("    }\n")
    f.write("    return NULL;\n")
    f.write("}\n")